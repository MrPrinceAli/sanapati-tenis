const built = new Map<string, Dict>();
export function getDict(locale: Locale, rules: Rules = DEFAULT_RULES): Dict {
  const key = `${locale}:${rules.maxDaysAhead}:${rules.maxDuration}:${rules.cancelLimitHours}:${rules.maxActiveBookings}`;
  let dict = built.get(key);
  if (!dict) {
    if (built.size > 50) built.clear();
    dict = (locale === "en" ? makeEn : makeId)(rules);
    built.set(key, dict);
  }
  return dict;
}

export type ErrorCode = keyof Dict["errors"];

export const opt = (t: Dict, value: string) => t.opt[value] ?? value;

// Alasan batal disimpan sebagai "<alasan> — <keterangan bebas>"; hanya bagian alasan yang diterjemahkan.
export function translateReason(t: Dict, stored: string): string {
  const [reason, ...detail] = stored.split(" — ");
  return [opt(t, reason), ...detail].join(" — ");
}

const pad = (n: number) => String(n).padStart(2, "0");

export function formatters(locale: Locale) {
  const intl = locale === "en" ? "en-GB" : "id-ID";
  const t = getDict(locale);
  const sep = locale === "en" ? ":" : ".";
  const day = (date: string, opts: Intl.DateTimeFormatOptions) =>
    new Intl.DateTimeFormat(intl, { ...opts, timeZone: "UTC" }).format(new Date(`${date}T12:00:00Z`));
  const hour = (h: number) => `${pad(h)}${sep}00`;

  return {
    hour,
    range: (start: number, end: number) => `${hour(start)} – ${hour(end)}`,
    /** Ringkas untuk kolom sempit: "22–23". */
    rangeShort: (start: number, end: number) => `${pad(start)}–${pad(end)}`,
    dateLong: (date: string) => day(date, { weekday: "long", day: "numeric", month: "long", year: "numeric" }),
    dateShort: (date: string) => day(date, { weekday: "short", day: "numeric", month: "short" }),
    weekday: (date: string) => day(date, { weekday: "short" }),
    dayNum: (date: string) => day(date, { day: "numeric" }),
    month: (date: string) => day(date, { month: "short" }),
    monthYear: (iso: string) => new Intl.DateTimeFormat(intl, { timeZone: TZ, month: "long", year: "numeric" }).format(new Date(iso)),
    timestamp: (iso: string) =>
      new Intl.DateTimeFormat(intl, {
        timeZone: TZ,
        day: "numeric",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      }).format(new Date(iso)),
    countdown: (ms: number) => {
      if (ms <= 0) return t.countdown.ongoing;
      const mins = Math.round(ms / 60000);
      if (mins < 60) return t.countdown.minutes(mins);
      const h = Math.floor(mins / 60);
      if (h < 24) return t.countdown.hours(h, mins % 60);
      return t.countdown.days(Math.floor(h / 24), h % 24);
    },
  };
}

export type Formatters = ReturnType<typeof formatters>;
